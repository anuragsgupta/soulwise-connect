/**
 * Get translation for a key in the specified language
 */
export function getTranslation(
  language: string,
  key: string,
  fallback?: string
): string {
  const dict = translations[language];
  if (dict && dict[key as TranslationKey]) {
    return dict[key as TranslationKey];
  }
  // Fallback to English
  return translations.en[key as TranslationKey] || fallback || key;
}

/**
 * Get all translations for a language
 */
export function getLanguageTranslations(language: string): TranslationDictionary {
  return translations[language] || translations.en;
}
